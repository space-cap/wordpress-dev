<!-- 바닐라 JS 아코디언 로직 -->
<script>
document.addEventListener('DOMContentLoaded', function() {
    const triggers = document.querySelectorAll('.accordion-trigger');
    
    triggers.forEach(trigger => {
        trigger.addEventListener('click', function() {
            const item = this.parentElement;
            const content = this.nextElementSibling;
            const arrow = this.querySelector('.accordion-arrow');
            
            const isOpen = !content.classList.contains('hidden');
            
            // 모든 아코디언 닫기 (원할 경우 주석 처리하여 다중 열기 허용 가능)
            document.querySelectorAll('.accordion-content').forEach(c => c.classList.add('hidden'));
            document.querySelectorAll('.accordion-arrow').forEach(a => a.classList.remove('rotate-180'));
            document.querySelectorAll('.accordion-item').forEach(i => i.classList.remove('bg-white', 'shadow-md'));
            
            if (!isOpen) {
                content.classList.remove('hidden');
                arrow.classList.add('rotate-180');
                item.classList.add('bg-white', 'shadow-md');
            }
        });
    });
});
</script>

